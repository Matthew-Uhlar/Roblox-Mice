#!/usr/bin/env python3
"""Renders the animated cosmetic thumbnails (iteration 6, team Preview).

    lune run scripts/render-cosmetics.luau           # -> build/cosmetic_scenes (git-ignored)
    python3 scripts/make-cosmetic-icons.py [scenesDir] [--preview DIR]

Every class skin, Ascension look, hat, trail and tint is drawn from the geometry
the game builds (scripts/render-cosmetics.luau: the server's BotModel in Herd
Suit mode + the client's Visuals/CosmeticParts) with the software renderer of
scripts/render-preview.py. Titles, dyes, chat tags and frames are text: the
client draws those (UI/CosmeticIcon).

Animation: FRAMES sprite frames per icon side by side (CELL px each): the hero
sways a little (yaw), a trail sweeps round it. Frame 0 is the still look
(Effects "off"). Same layout and index schema as scripts/make-icons.py, so
UI/AnimatedIcon can step them too.

Writes assets/icons/icon_cos_atlas_<n>.png, src/client/UI/CosmeticIconAtlas.luau
and the icon_cos_atlas_* Image entries of assets/models/manifest.json (other
entries untouched). Upload them with the "Upload assets" workflow; until their
ids are in Config/AssetIds the client draws the icons in code.

Stable layout (iteration 7): an icon already in CosmeticIconAtlas.luau keeps its
atlas page and cell; new icons go on NEW pages after the last existing one, so
uploaded pages never change layout (the upload workflow skips names that already
have an id) and only the new pages need uploading. `--relayout` packs everything
from scratch (then every page must be re-uploaded under new names).
"""

import importlib.util
import json
import re
import multiprocessing
import os
import subprocess
import sys

import numpy as np
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_spec = importlib.util.spec_from_file_location("render_preview", os.path.join(ROOT, "scripts", "render-preview.py"))
R = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(R)

OUT_DIR = os.path.join(ROOT, "assets", "icons")
ATLAS_LUAU = os.path.join(ROOT, "src", "client", "UI", "CosmeticIconAtlas.luau")
MANIFEST = os.path.join(ROOT, "assets", "models", "manifest.json")
PREFIX = "icon_cos_atlas_"

CELL = 128
FRAMES = 4
ATLAS = 1024
PER_ROW = ATLAS // (CELL * FRAMES)  # 2
ROWS = ATLAS // CELL  # 8
SLOTS = PER_ROW * ROWS - 1  # 15 icons per atlas: the last slot holds the glow sprite
GLOW_XY = ((PER_ROW - 1) * CELL * FRAMES, (ROWS - 1) * CELL)  # same place as make-icons.py

SWAY = [28, 38, 48, 38]  # yaw per frame (ping-pong)
PITCH = {"hat": 14, "trail": 38}
ORDER = {"skin": 0, "look": 1, "hat": 2, "trail": 3, "tint": 4}


def card(img):
    """Rounded-corner card with a thin ink rim (the UI adds its own stroke too)."""
    img = img.convert("RGBA").resize((CELL, CELL), Image.LANCZOS)
    s = 4
    mask = Image.new("L", (CELL * s, CELL * s), 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, CELL * s - 1, CELL * s - 1), radius=18 * s, fill=255)
    mask = mask.resize((CELL, CELL), Image.LANCZOS)
    img.putalpha(mask)
    rim = Image.new("RGBA", (CELL * s, CELL * s), (0, 0, 0, 0))
    ImageDraw.Draw(rim).rounded_rectangle(
        (s, s, CELL * s - 1 - s, CELL * s - 1 - s), radius=18 * s, outline=(62, 38, 22, 200), width=3 * s
    )
    img.alpha_composite(rim.resize((CELL, CELL), Image.LANCZOS))
    return img


def frames_of(scene):
    slot = scene.get("slot")
    pitch = PITCH.get(slot, 18)
    out = []
    if scene.get("frames"):
        for parts in scene["frames"]:
            R.MAT_IDS.clear()
            out.append(card(R.render_object({"parts": parts}, (CELL, CELL), yaw=32, pitch=pitch, scale=0.9)))
    else:
        for yaw in SWAY:
            R.MAT_IDS.clear()
            sc = 1.0 if slot == "hat" else 0.92
            out.append(card(R.render_object({"parts": scene["parts"]}, (CELL, CELL), yaw=yaw, pitch=pitch, scale=sc)))
    return out


def glow_sprite():
    """The soft hover glow UI/AnimatedIcon draws behind an icon (as in make-icons.py)."""
    n = CELL
    ys, xs = np.mgrid[0:n, 0:n].astype(np.float32)
    d = np.hypot(xs - n / 2 + 0.5, ys - n / 2 + 0.5) / (n / 2)
    a = np.clip(1 - d, 0, 1) ** 2.2
    out = np.zeros((n, n, 4), np.uint8)
    out[..., :3] = 255
    out[..., 3] = (a * 0.9 * 255).astype(np.uint8)
    return Image.fromarray(out, "RGBA")


def write_luau(entries, n_atlas):
    lines = [
        "--!strict",
        "-- GENERATED by scripts/make-cosmetic-icons.py: do not edit by hand.",
        "-- Rendered cosmetic thumbnails (assets/icons/icon_cos_atlas_*.png, uploaded as the",
        "-- manifest's icon_cos_atlas_* Images). Same schema as UI/IconAtlas: each icon's",
        "-- frames sit side by side from (x, y), `cell` px square. UI/CosmeticIcon reads it.",
        "return {",
        f"\tcell = {CELL},",
        f"\tsize = {ATLAS},",
        f"\tglow = {{ x = {GLOW_XY[0]}, y = {GLOW_XY[1]} }},",
        "\tatlases = { " + ", ".join(f'"{PREFIX}{i + 1}"' for i in range(n_atlas)) + " },",
        "\ticons = {",
    ]
    for name in sorted(entries):
        e = entries[name]
        lines.append(
            f'\t\t["{name}"] = {{ atlas = "{e["atlas"]}", x = {e["x"]}, y = {e["y"]}, frames = {FRAMES}, '
            f'anim = "wave", motion = "none", fps = {e["fps"]}, hold = 0, '
            f'glow = {{ {e["glow"][0]}, {e["glow"][1]}, {e["glow"][2]} }} }},'
        )
    lines += ["\t},", "}", ""]
    with open(ATLAS_LUAU, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    try:  # keep scripts/check.sh's `stylua --check` green
        subprocess.run(["stylua", ATLAS_LUAU], check=False)
    except OSError:
        print("stylua not found: run `stylua " + os.path.relpath(ATLAS_LUAU, ROOT) + "`")


def write_manifest(n_atlas):
    data = json.load(open(MANIFEST, encoding="utf-8"))
    wrapped = isinstance(data, dict)
    entries = data.get("assets", []) if wrapped else data
    out = [e for e in entries if not str(e.get("name", "")).startswith(PREFIX)]
    for i in range(n_atlas):
        name = f"{PREFIX}{i + 1}"
        out.append(
            {
                "name": name,
                "path": f"../icons/{name}.png",
                "type": "Image",
                "description": f"Trunkfall cosmetic thumbnails: {name}",
            }
        )
    data = {"assets": out} if wrapped else out
    with open(MANIFEST, "w", encoding="utf-8") as fh:
        json.dump(data, fh, indent=2)
        fh.write("\n")


def existing_layout():
    """name -> (page index 0-based, x, y) from the current CosmeticIconAtlas.luau."""
    if not os.path.exists(ATLAS_LUAU):
        return {}
    src = open(ATLAS_LUAU, encoding="utf-8").read()
    pat = re.compile(
        r'\["(icon_cos_\w+)"\]\s*=\s*\{\s*atlas\s*=\s*"' + PREFIX + r'(\d+)",\s*x\s*=\s*(\d+),\s*y\s*=\s*(\d+)'
    )
    return {m.group(1): (int(m.group(2)) - 1, int(m.group(3)), int(m.group(4))) for m in pat.finditer(src)}


def slot_of(x, y):
    return (y // CELL) * PER_ROW + x // (CELL * FRAMES)


def main(argv):
    args = [a for a in argv if not a.startswith("--")]
    src = args[0] if args else os.path.join(ROOT, "build", "cosmetic_scenes")
    scenes = []
    for f in sorted(os.listdir(src)):
        if f.endswith(".json"):
            with open(os.path.join(src, f), encoding="utf-8") as fh:
                scenes.append(json.load(fh))
    if not scenes:
        sys.exit("no scenes: run `lune run scripts/render-cosmetics.luau " + src + "` first")
    scenes.sort(key=lambda s: (ORDER.get(s.get("slot"), 9), s["name"]))
    atlases, entries = [], {}
    glow = glow_sprite()
    with multiprocessing.Pool() as pool:
        rendered = pool.map(frames_of, scenes)
    old = {} if "--relayout" in argv else existing_layout()
    places = {}
    used = set()
    for sc in scenes:
        p = old.get(sc["name"])
        if p and 0 <= slot_of(p[1], p[2]) < SLOTS and (p[0], slot_of(p[1], p[2])) not in used:
            places[sc["name"]] = (p[0], slot_of(p[1], p[2]))
            used.add(places[sc["name"]])
    first_new = (max(p[0] for p in old.values()) + 1) if old else 0
    nxt = first_new * SLOTS
    for sc in scenes:
        if sc["name"] not in places:
            places[sc["name"]] = divmod(nxt, SLOTS)
            nxt += 1
    n_pages = max([p[0] for p in places.values()] + [first_new - 1]) + 1
    for _ in range(n_pages):
        atlases.append(Image.new("RGBA", (ATLAS, ATLAS), (0, 0, 0, 0)))
        atlases[-1].alpha_composite(glow, GLOW_XY)
    for i, sc in enumerate(scenes):
        a, slot = places[sc["name"]]
        row, col = divmod(slot, PER_ROW)
        x0, y0 = col * CELL * FRAMES, row * CELL
        for k, fr in enumerate(rendered[i]):
            atlases[a].alpha_composite(fr, (x0 + k * CELL, y0))
        g = [int(v) for v in (sc.get("glow") or [255, 220, 120])[:3]]
        entries[sc["name"]] = {
            "atlas": f"{PREFIX}{a + 1}",
            "x": x0,
            "y": y0,
            "fps": 6 if sc.get("slot") == "trail" else 3,
            "glow": g,
        }
    os.makedirs(OUT_DIR, exist_ok=True)
    keep = set()
    for i, im in enumerate(atlases):
        name = f"{PREFIX}{i + 1}.png"
        im.save(os.path.join(OUT_DIR, name), optimize=True)
        keep.add(name)
    for f in os.listdir(OUT_DIR):
        if f.startswith(PREFIX) and f.endswith(".png") and f not in keep:
            os.remove(os.path.join(OUT_DIR, f))
    write_luau(entries, len(atlases))
    write_manifest(len(atlases))
    print(f"{len(entries)} cosmetic icons in {len(atlases)} atlases -> assets/icons, {os.path.relpath(ATLAS_LUAU, ROOT)}")
    if "--preview" in argv:
        out = argv[argv.index("--preview") + 1]
        os.makedirs(out, exist_ok=True)
        sheet = Image.new("RGBA", (ATLAS, ATLAS * len(atlases)), (236, 228, 214, 255))
        for i, im in enumerate(atlases):
            sheet.alpha_composite(im, (0, i * ATLAS))
        sheet.convert("RGB").save(os.path.join(out, "cosmetic_icons_sheet.png"))


if __name__ == "__main__":
    np.seterr(all="ignore")
    main(sys.argv[1:])
